"""Measure the catalog against the brief's criteria and write coverage/metrics.md.

Coverage per UI screen is keyword-mapped from action ids, so it is approximate:
it shows where actions exist, not that every button on a screen is covered.

Usage: python3 scripts/stats.py
"""
import collections
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# The 23 screens of the app's sidebar (coverage/map.md), mapped to action ids.
SCREENS = [
    ("CRM", "Contacts", r"^contacts\.(?!.*(list|folder|segment))"),
    ("CRM", "Lists", r"^contacts\..*(list|folder)"),
    ("CRM", "Segments", r"^segments\.|^contacts\.get_segments$"),
    ("CRM", "Companies", r"^companies\."),
    ("CRM", "Deals", r"^deals\."),
    ("CRM", "Tasks", r"^tasks\."),
    ("CRM", "Custom objects", r"^custom_objects\."),
    ("Marketing", "Campaigns", r"^(email_campaigns|sms_campaigns|whats_app_campaigns)\."),
    ("Marketing", "Landing pages", r"landing"),
    ("Marketing", "Forms", r"^forms\."),
    ("Marketing", "Statistics", r"(report|stats|statistic)"),
    ("Marketing", "Templates", r"template"),
    ("Automations", "Automations", r"^automations\."),
    ("Transactional", "Email", r"^transactional_emails\."),
    ("Transactional", "SMS", r"^transactional_sms\."),
    ("Conversations", "Inbox", r"^conversations\."),
    ("Conversations", "Phone", r"phone"),
    ("Conversations", "Meetings", r"meeting"),
    ("Commerce", "E-commerce", r"^(ecommerce|coupons|payments)\."),
    ("Commerce", "Loyalty", r"^(program|balance|tier|reward)\."),
    ("Library", "Media", r"^files\."),
    ("Analytics", "Conversions and studio", r"(attribution|conversion)"),
    ("Settings", "Account, senders, domains, webhooks, users", r"^(senders|domains|webhooks|user|master_account|account|"
                                                                r"inbound_parsing|external_feeds|consent_groups)\."),
]


def main():
    actions = [json.loads(p.read_text()) for p in (ROOT / "catalog").rglob("*.json")]
    level = collections.Counter(a["verification"]["level"] for a in actions)
    internal_only = [a for a in actions if a["execution"]["method"] != "public_api"
                     and not any(x.get("method") == "public_api" for x in a.get("alternative_executions", []))]
    n = len(actions)

    rows, with_any, with_exec = [], 0, 0
    for area, screen, pattern in SCREENS:
        hits = [a for a in actions if re.search(pattern, a["id"])]
        executed = sum(a["verification"]["level"] == "executed" for a in hits)
        with_any += bool(hits)
        with_exec += bool(executed)
        rows.append(f"| {area} | {screen} | {len(hits)} | {executed} |")

    lines = [
        "# Metrics",
        "",
        "Generated by `scripts/stats.py` from `catalog/`. Do not edit by hand.",
        "",
        "## Catalog",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Actions | {n} |",
        f"| Verified on the live account (`executed`) | {level['executed']} ({level['executed'] / n:.0%}) |",
        f"| Seen in the UI, not run on purpose (`observed`) | {level['observed']} |",
        f"| From the public spec, not run (`documented`) | {level['documented']} |",
        f"| Public API operations covered | {sum(1 for a in actions if a['execution']['method'] == 'public_api') + sum(1 for a in actions if any(x.get('method') == 'public_api' for x in a.get('alternative_executions', [])))} of 287 |",
        f"| Actions with no public API equivalent (found by reverse engineering) | {len(internal_only)} |",
        f"| Flagged destructive (delete or send) | {sum(a.get('destructive', False) for a in actions)} |",
        f"| With observed error cases and recovery advice | {sum('errors' in a for a in actions)} |",
        f"| Plan-gated | {sum('plan_gated' in a for a in actions)} |",
        f"| Real responses that contradict the public spec's schema | "
        f"{sum('differs from the documented output schema' in a['verification'].get('notes', '') for a in actions)} |",
        "",
        "## UI coverage (23 sidebar screens, keyword-mapped)",
        "",
        f"Screens with at least one action: **{with_any} of {len(SCREENS)}**. "
        f"Screens with at least one action verified on the live account: **{with_exec} of {len(SCREENS)}**.",
        "",
        "| Area | Screen | Actions | Executed |",
        "|---|---|---|---|",
        *rows,
        "",
        "## Blind-agent evaluation (EVAL.md)",
        "",
        "| Round | Tasks complete or correctly handed to the user |",
        "|---|---|",
        "| 1 | 1 of 6 |",
        "| 2 | 5 of 6 |",
    ]
    (ROOT / "coverage" / "metrics.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
